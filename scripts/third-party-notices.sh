#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES from the license files of every module
# linked into cmd/kenaz on darwin, linux and windows.
# `make check-notices` fails if the committed file is stale.
set -euo pipefail
cd "$(dirname "$0")/.."
modcache=$(go env GOMODCACHE)
mods=$(for os in darwin linux windows; do
  GOOS=$os go list -deps -f '{{if .Module}}{{if not .Module.Main}}{{.Module.Path}}@{{.Module.Version}}{{end}}{{end}}' ./cmd/kenaz
done | sort -u)
{
  echo "THIRD-PARTY NOTICES for the public kenaz-plugin sources"
  echo
  echo "Generated by scripts/third-party-notices.sh. Official release builds"
  echo "append notices for the proprietary module."
  for m in $mods; do
    # Module cache paths case-encode uppercase letters as !lowercase.
    dir="$modcache/$(printf %s "$m" | perl -pe 's/([A-Z])/!\l$1/g')"
    lic=$(ls "$dir" | grep -iE '^(LICEN[CS]E|COPYING)(\.md|\.txt)?$' | head -1 || true)
    echo
    echo "================================================================"
    echo "$m"
    echo "================================================================"
    if [ -z "$lic" ]; then echo "ERROR: no license file found" >&2; exit 1; fi
    cat "$dir/$lic"
  done
} > "${1:-THIRD_PARTY_NOTICES}"
